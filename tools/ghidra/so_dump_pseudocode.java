// so_dump_pseudocode.java -- dump decompiled pseudocode for named functions
//
// Produces a plain-text appendix of pseudocode for every function whose name
// carries real semantics (not FUN_/frag_/leaf_/tail_/cff_/dl_/vm_ etc.),
// so the report can include a readable code appendix.
//
// Config: $TMP/so_dump_pseudo.cfg
//   out=path          output file
//   min_size=64       minimum body size
//   include_vm=0      include vm_* handlers
//@category MobileRE

import ghidra.app.script.GhidraScript;
import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionIterator;
import ghidra.program.model.listing.FunctionManager;
import ghidra.program.model.listing.Instruction;
import ghidra.program.model.listing.Listing;
import java.io.File;
import java.io.FileInputStream;
import java.io.InputStream;
import java.io.PrintWriter;
import java.util.*;

public class so_dump_pseudocode extends GhidraScript {

    /** Count real instructions in a function body (bounded). */
    private int insnCount(Function f) {
        ghidra.program.model.listing.Listing lst = currentProgram.getListing();
        Instruction ins = lst.getInstructionAt(f.getEntryPoint());
        int n = 0;
        while (ins != null && n < 4000 && f.getBody().contains(ins.getAddress())) {
            n++;
            ins = ins.getNext();
        }
        return n;
    }

    private boolean isSemantic(String n, boolean includeVm) {
        if (n.startsWith("thunk_") || n.startsWith("LAB_") || n.startsWith("switchD_")) return false;
        if (!includeVm && n.startsWith("vm_")) return false;
        if (n.startsWith("_Z")) return false;      // C++ mangled std
        if (n.startsWith("__cxa") || n.startsWith("__gxx")) return false;
        // FUN_, _INIT, dl_, mprot_ are real functions even when unnamed
        return true;
    }

    @Override
    public void run() throws Exception {
        String tmp = System.getenv("TMP");
        if (tmp == null) tmp = System.getProperty("java.io.tmpdir");
        Properties cfg = new Properties();
        File cfgf = new File(tmp, "so_dump_pseudo.cfg");
        if (cfgf.isFile()) {
            try (InputStream in = new FileInputStream(cfgf)) { cfg.load(in); }
        }
        String outPath = cfg.getProperty("out", new File(tmp, "pseudocode.txt").getPath());
        int minSize = Integer.parseInt(cfg.getProperty("min_size", "64"));
        boolean includeVm = "1".equals(cfg.getProperty("include_vm", "0"));

        FunctionManager fm = currentProgram.getFunctionManager();
        DecompInterface dec = new DecompInterface();
        dec.openProgram(currentProgram);

        List<Function> picked = new ArrayList<>();
        FunctionIterator it = fm.getFunctions(true);
        while (it.hasNext()) {
            Function f = it.next();
            if (f.isExternal() || f.isThunk()) continue;
            if (f.getBody().getNumAddresses() < minSize) continue;
            if (!isSemantic(f.getName(), includeVm)) continue;
            // fragment-named functions are only worth dumping when they hold
            // real code; stubs (<32 insns) carry no information
            String nm = f.getName();
            if (nm.startsWith("frag_") || nm.startsWith("leaf_")
                    || nm.startsWith("tail_") || nm.startsWith("cff_")) {
                if (insnCount(f) < 8) continue;
            }
            picked.add(f);
        }
        picked.sort(Comparator.comparing(Function::getName));

        int ok = 0, fail = 0;
        try (PrintWriter pw = new PrintWriter(new File(outPath), "UTF-8")) {
            pw.println("// decompiled pseudocode (semantic functions)");
            pw.println("// generated by so_dump_pseudocode.java");
            pw.println("// functions: " + picked.size());
            pw.println();
            for (Function f : picked) {
                pw.printf("// ===========================================================%n");
                pw.printf("// %s  @ %s  (%d bytes)%n",
                        f.getName(), f.getEntryPoint(), f.getBody().getNumAddresses());
                pw.printf("// ===========================================================%n");
                DecompileResults dr = dec.decompileFunction(f, 60, monitor);
                if (dr != null && dr.decompileCompleted() && dr.getDecompiledFunction() != null) {
                    pw.println(dr.getDecompiledFunction().getC());
                    ok++;
                } else {
                    pw.println("// <decompile failed>");
                    fail++;
                }
                pw.println();
            }
        }
        println(String.format("dumped %d functions (ok=%d fail=%d) -> %s",
                picked.size(), ok, fail, outPath));
    }
}
